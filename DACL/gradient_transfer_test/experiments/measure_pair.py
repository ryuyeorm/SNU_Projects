"""Run one matched source-to-target transfer measurement.

This is the central experimental unit.  It probes a fresh target learner, measures
early gradient compatibility, snapshots all training state, then compares ordinary
actor–critic against actor–critic plus the matching source-policy KL regularizer.
"""

from __future__ import annotations

import argparse
import copy
import json
from pathlib import Path

import numpy as np
import torch

from gradient_transfer_test.agents.sac import Actor, ReplayBuffer, set_seed
from gradient_transfer_test.experiments.common import (auc, interact_train, load_config, make_agent,
                                                        make_env, train_with_evaluations,
                                                        collect_diagnostic_rollout)
from gradient_transfer_test.transfer import freeze_actor, measure_alignment


def load_prior(path, device="cpu"):
    """Reconstruct and freeze a source actor checkpoint.

    Args:
        path: Source checkpoint written by ``train_source``.
        device: PyTorch device on which target evaluation and KL run.
    """
    ckpt = torch.load(path, map_location=device, weights_only=False)
    actor = Actor(hidden_sizes=tuple(ckpt["hidden_sizes"])).to(device)
    actor.load_state_dict(ckpt["actor"])
    return freeze_actor(actor)


def _branch(agent_state, replay_state, config, target_angle, seed, prior, strength):
    """Restore one branch snapshot and produce its post-probe learning curve.

    Args:
        agent_state: Deep-copied network, optimizer, entropy, and RNG snapshot.
        replay_state: Deep-copied probe replay and sampler state.
        config: Full parsed configuration.
        target_angle: Action-dynamics rotation of the target task.
        seed: Matched branch seed.
        prior: Frozen source actor or ``None``.
        strength: KL coefficient; zero defines scratch.
    """
    agent = make_agent(config, seed)
    agent.load_state_dict(copy.deepcopy(agent_state), restore_rng=True)
    replay = ReplayBuffer(capacity=config["experiment"]["replay_capacity"], seed=seed)
    replay.load_state_dict(replay_state)
    curve, alignment_curve = train_with_evaluations(
        agent, replay, config, target_angle, seed, prior if strength else None,
        strength, diagnostic_prior=prior
    )
    return curve, alignment_curve


def measure_pair(config, source_checkpoint, target_angle, seed):
    """Measure compatibility and actual transfer for one task-pair seed.

    Args:
        config: Full parsed YAML configuration.
        source_checkpoint: Path to a trained source actor.
        target_angle: Target action-dynamics rotation in degrees.
        seed: Independent target learner/probe/branch seed.

    Returns:
        Flat result dictionary suitable for one CSV row. Learning curves are encoded
        as JSON strings so the CSV remains self-contained.
    """
    exp = config["experiment"]
    # Stage B: create a fresh target learner and gather its probe experience.
    prior = load_prior(source_checkpoint, config.get("device", "cpu"))
    learner = make_agent(config, seed)
    replay = ReplayBuffer(capacity=exp["replay_capacity"], seed=seed)
    interact_train(learner, make_env(config, target_angle), replay, exp["probe_steps"],
                   exp["batch_size"], exp["learning_starts"], seed)
    if getattr(learner, "on_policy", False):
        # Old rollout actions were generated by earlier policy versions. Replace them
        # with a fresh, update-free rollout from the exact actor being diagnosed.
        replay.clear()
        collect_diagnostic_rollout(
            learner, make_env(config, target_angle), replay,
            exp.get("diagnostic_rollout_steps", exp["probe_batch_size"]),
            seed + 50_000,
        )
    # Both gradients within every pair consume identical replay states.
    alignment = measure_alignment(
        learner, prior, replay, exp["probe_batch_size"],
        exp["num_alignment_batches"],
        num_action_samples=exp.get("diagnostic_action_samples", 1),
        transfer_measure=exp.get("transfer_measure", "kl"),
    )
    agent_state, replay_state = copy.deepcopy(learner.state_dict()), replay.state_dict()

    # Each branch restores the exact same model, optimizer, replay, and RNG snapshots.
    scratch, scratch_alignment = _branch(
        agent_state, replay_state, config, target_angle, seed, prior, 0.0
    )
    transfer, transfer_alignment = _branch(
        agent_state, replay_state, config, target_angle, seed, prior,
        exp["transfer_lambda"]
    )
    # Assemble all primary and secondary metrics into one machine-readable row.
    source_angle = float(torch.load(source_checkpoint, map_location="cpu", weights_only=False)["angle"])
    early_idx = min(1, len(scratch) - 1)
    record = {
        "source_angle": source_angle, "target_angle": float(target_angle), "seed": int(seed),
        "transfer_measure": exp.get("transfer_measure", "kl"),
        **alignment,
        "scratch_auc": auc(scratch), "transfer_auc": auc(transfer),
        "scratch_final_return": scratch[-1]["return"], "transfer_final_return": transfer[-1]["return"],
        "scratch_early_return": scratch[early_idx]["return"], "transfer_early_return": transfer[early_idx]["return"],
        "scratch_curve": json.dumps(scratch), "transfer_curve": json.dumps(transfer),
        "scratch_alignment_curve": json.dumps(scratch_alignment),
        "transfer_alignment_curve": json.dumps(transfer_alignment),
    }
    record["delta_auc"] = record["transfer_auc"] - record["scratch_auc"]
    record["final_return_difference"] = record["transfer_final_return"] - record["scratch_final_return"]
    record["early_return_difference"] = record["transfer_early_return"] - record["scratch_early_return"]
    threshold = exp.get("success_rate_threshold", 0.8)
    def threshold_step(curve):
        """Return first configured evaluation step reaching the success threshold."""
        return next((p["step"] for p in curve if p["success_rate"] >= threshold), np.nan)
    record["scratch_steps_to_success"] = threshold_step(scratch)
    record["transfer_steps_to_success"] = threshold_step(transfer)
    # This is now separation between dynamics rotations, not between goal positions.
    record["angular_separation"] = min(abs(source_angle - target_angle) % 360,
                                       360 - abs(source_angle - target_angle) % 360)
    if scratch_alignment:
        # These post-start summaries are descriptive diagnostics, not purely early
        # predictors. The unprefixed initial alignment remains the primary variable.
        record["scratch_time_mean_alignment"] = float(np.mean(
            [point["mean_cosine_alignment"] for point in scratch_alignment]
        ))
        record["transfer_time_mean_alignment"] = float(np.mean(
            [point["mean_cosine_alignment"] for point in transfer_alignment]
        ))
    return record


def main():
    """Parse command-line arguments and print one pair record as JSON."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", default="configs/default.yaml")
    parser.add_argument("--source-checkpoint", required=True)
    parser.add_argument("--target-angle", required=True, type=float)
    parser.add_argument("--seed", required=True, type=int)
    args = parser.parse_args()
    print(json.dumps(measure_pair(load_config(args.config), args.source_checkpoint,
                                  args.target_angle, args.seed), indent=2))


if __name__ == "__main__":
    main()
